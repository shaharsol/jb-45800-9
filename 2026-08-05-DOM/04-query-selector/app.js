// lets say i want to modify the span
const mySpan = document.querySelector('span')
console.log(mySpan)

// querySelector gets the 1st element it finds
const myDiv = document.querySelector('div')
console.log(myDiv)

// querySelectorAll gets a flat array (no hierarchy) of all items picked
// by the selector
const myDivs = document.querySelectorAll('div')
console.log(myDivs)


